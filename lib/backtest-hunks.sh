#!/usr/bin/env bash
# 從 unified diff 的 hunk header 取出新檔側的行號區間。
#
# hunk header 形如 `@@ -92,7 +92,7 @@`。省略長度時（`@@ -10 +10 @@`）長度為 1。
# 只看新檔側（+ 那一半），因為要問的是「後來的 fix 改到了這個 PR 新寫的哪幾行」。
#
# 區間交集的判定不放在這裡：正式路徑是 lib/backtest-groundtruth.sh 的
# backtest_overlap，吃的是 {"<path>": [[起,迄], ...]} 這種帶檔名的 JSON，
# 由 scripts/build-benchmark.sh 呼叫。這裡只負責「一份 patch 產出哪些行號區間」，
# 不知道檔名，也就無法做正式路徑真正需要的「同檔案才比」那一層。

backtest_hunks_of() {
  grep -oE '^@@ -[0-9,]+ \+[0-9]+(,[0-9]+)? @@' \
    | sed -E 's/^@@ -[0-9,]+ \+([0-9]+)(,([0-9]+))? @@/\1 \3/' \
    | awk '{ len = ($2 == "" ? 1 : $2); if (len > 0) print $1, $1 + len - 1 }'
}
# 注意：純刪除的 hunk（`@@ -5,3 +5,0 @@`）長度為 0，不產生區間。
# PR 純粹刪除行時不引入新行，無可指派行號的概念，所以區間集為空。
# 這是誠實的結果，不是遺漏。
#
# 長度 0 的處理是「不產生區間」而不是「把起迄對調成一個合法區間」，
# 因為對調會憑空生出一段從未寫入的行區間，正好是會發明缺陷的那種錯。
# 這也讓輸出恆滿足 起 <= 迄，下游 backtest_overlap 的 jq 比對式才能省掉
# 逆序守衛：逆序區間餵進那個比對式會被判成跟一大段行號都重疊。
# 這個不變量由 tests/test_backtest_hunks.sh 用行為斷言釘住。
